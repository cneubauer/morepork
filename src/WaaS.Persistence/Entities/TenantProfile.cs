        public ulong? LifetimeInSeconds { get; set; } = null;

        /// <summary>
        /// Max count of cron jobs per single webspace.
        /// </summary>
        public int? CronJobsPerWebspace { get; set; } = 100;

        /// <summary>
        /// The maximum ratelimit for the WAF, which the tenant can set.
        /// </summary>
        public uint? MaxWafRatelimit { get; set; } = 100;
    }

    public class DefaultsInfo
    {
