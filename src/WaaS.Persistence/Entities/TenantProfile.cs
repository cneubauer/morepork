/// <summary>
/// Model for the tenant profile with attached default values.
/// Be careful by changing the default values. It can have a big impact on our tenants.
/// </summary>
public class TenantProfile
{
    /// <summary>
    /// It can be a company name, a team name or something else.
    /// A partner can have several tenants.
    /// Example:
    /// - Partner Name = UDAG
    ///   - Tenant Name 1: base_udag
    ///   - Tenant Name 2: sandbox_udag
    /// </summary>
    public string? PartnerName { get; set; } = string.Empty;

    /// <summary>
    /// Flag whether the given tenant is a test tenant.
    /// In some use cases there is a difference in behavior between live and test tenants.
    /// </summary>
    public bool? TestTenant { get; set; } = true;

    /// <summary>
    /// DEPRECATED, see DataAccessDomainFormats.
    /// </summary>
    public string? DataAccessDomainFormat { get; set; } = "access-{SYSTEM-INSTANCE-ID}.webspace-host.com";

    /// <summary>
    /// Formats of product subdomains for data access.
    /// </summary>
    public List<string>? DataAccessDomainFormats { get; set; } = ["access-{SYSTEM-INSTANCE-ID}.webspace-host.com"];

    /// <summary>
    /// DEPRECATED, see HttpAccessDomainFormats.
    /// </summary>
    public string? HttpAccessDomainFormat { get; set; } = "home-{SYSTEM-INSTANCE-ID}.webspace-host.com";

    /// <summary>
    /// Formats of product subdomains for http access.
    /// </summary>
    public List<string>? HttpAccessDomainFormats { get; set; } = ["home-{SYSTEM-INSTANCE-ID}.webspace-host.com"];

    /// <summary>
    /// DEPRECATED, see DatabaseAccessDomainFormats.
    /// </summary>
    public string? DatabaseAccessDomainFormat { get; set; } = "database-{SYSTEM-INSTANCE-ID}.webspace-host.com";

    /// <summary>
    /// Formats of product subdomains for database access.
    /// </summary>
    public List<string>? DatabaseAccessDomainFormats { get; set; } = ["database-{SYSTEM-INSTANCE-ID}.webspace-host.com"];

    /// <summary>
    /// Default lifetime of temporary accounts in seconds.
    /// </summary>
    public long? TemporaryAccountLifetimeDefault { get; set; } = 14400;

    /// <summary>
    /// Default lifetime of temporary webspaces in seconds.
    /// </summary>
    public long? TemporaryWebspaceLifetimeDefault { get; set; } = 604800;

    /// <summary>
    /// If true, no notifications are generated by temporary errors.
    /// </summary>
    public bool? SuppressTempErrorNotifications { get; set; } = true;

    /// <summary>
    /// If true, no notifications are generated by the cleanup process.
    /// </summary>
    public bool? SuppressCleanupNotifications { get; set; } = true;

    /// <summary>
    /// If true, the tenant is able to set tags on the Stack Instance level.
    /// </summary>
    public bool? StackInstanceTagsAllowed { get; set; } = false;

    /// <summary>
    /// If true (default), the tenant is able to enable or disable Biofilter.
    /// </summary>
    public bool? BiofilterConfigurationAllowed { get; set; } = false;

    /// <summary>
    /// If true, the tenant is able to use compat links, when creating webspaces.
    /// </summary>
    public bool? CompatLinksAllowed { get; set; } = false;

    /// <summary>
    /// If true, the tenant is able to manage cdn mappings.
    /// </summary>
    public bool? CdnMappingsAllowed { get; set; } = false;

    /// <summary>
    /// If true, the tenant is able to change region within the same Stack Instance zone.
    /// </summary>
    public bool? DatabaseRegionAllowed { get; set; } = false;

    /// <summary>
    /// If true, the tenant is able to change region within the same Stack Instance zone.
    /// </summary>
    public bool? WebspaceRegionAllowed { get; set; } = false;

    /// <summary>
    /// Object for limits.
    /// </summary>
    public LimitsInfo? Limits { get; set; } = new LimitsInfo();

    /// <summary>
    /// Object for default values.
    /// </summary>
    public DefaultsInfo? Defaults { get; set; } = new DefaultsInfo();

    public class LimitsInfo
    {
        /// <summary>
        /// Max resource level per webspace. Currently the following values are supported: XS, S, M, L, XL and XXL.
        /// </summary>
        public string? ResourceLevel { get; set; } = "M";

        /// <summary>
        /// Max resource level per database. Currently the following values are supported: S and M.
        /// </summary>
        public string? DatabaseResourceLevel { get; set; } = "S";

        /// <summary>
        /// Max disk quota per webspace in bytes.
        /// </summary>
        public ulong? DiskQuotaInBytes { get; set; } = 2199023255552; // 2 TB

        /// <summary>
        /// Max database quota in bytes.
        /// </summary>
        public ulong? DatabaseQuotaInBytes { get; set; } = 1000000000;

        /// <summary>
        /// Max count of webspaces per Stack Instance.
        /// </summary>
        public int? WebspacesPerStack { get; set; } = 5000;

        /// <summary>
        /// Max count of stretchspaces per Stack Instance.
        /// </summary>
        public int? StretchSpacesPerStack { get; set; } = 5000;

        /// <summary>
        /// Max count of databases per Stack Instance.
        /// </summary>
        public int? DatabasesPerStack { get; set; } = 5000;

        /// <summary>
        /// Max count of domains per single webspace.
        /// </summary>
        public int? DomainsPerWebspace { get; set; } = 5000;

