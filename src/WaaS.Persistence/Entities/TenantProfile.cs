using System.Text.RegularExpressions;

namespace WaaS.Persistence;

public interface IHashValidation
{
    string SystemType { get; set; }
    bool IsValidHash(string hash);
}

public partial class CryptHashOptions : IHashValidation
{
    public const int DefaultRounds = 32768; // 2^15

    [GeneratedRegex(@"^\$(?<scheme>[0-9a-z])\$rounds=(?<rounds>\d+)\$[a-zA-Z0-9./]+\$[a-zA-Z0-9./]+$")]
    private static partial Regex CryptHashRegEx();

    public required string SystemType { get; set; }

    public string SchemeId { get; set; } = "5";

    // As a base value, be use our default rounds value used by the password store.
    // See https://git.ionos.org/WCLI/waas-crypt/src/branch/master/WaaS.Crypt/BusinessLogic/HashGenerator.cs
    // 2^15 = 32768
    public int MinRounds { get; set; } = (int)Math.Round(DefaultRounds * 0.5);
    public int MaxRounds { get; set; } = DefaultRounds * 2;

    public bool IsValidHash(string hash)
    {
        var matches = CryptHashRegEx().Matches(hash);

        if (matches.Count == 0)
            return false;

        var match = matches[0];

        if (match.Groups["scheme"].Value != SchemeId)
            return false;
            
        var rounds = int.Parse(match.Groups["rounds"].Value);

        if (rounds < MinRounds)
            return false;

        if (rounds > MaxRounds)
            return false;

        return true;
    }
}

