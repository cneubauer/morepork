        /// <summary>
        /// Default disk quota per webspace in bytes.
        /// </summary>
        public ulong? DiskQuotaInBytes { get; set; } = 50000000;

        /// <summary>
        /// Default database quota in bytes.
        /// </summary>
        public ulong? DatabaseQuotaInBytes { get; set; } = 1000000000;

