    public List<QuotaProfile>? QuotaProfiles { get; set; } = null;

    public class QuotaProfile
    {
        /// <summary>
        /// Quota profile name.
        /// </summary>
        public string? Name { get; set; } = string.Empty;

        /// <summary>
        /// It is for future use. Currently there is only one algorithm for quota increase / decrease.
        /// </summary>
        public string? AlgorithmType { get; set; } = "default";

        /// <summary>
        /// It is a value in percent after which the quota is increased automatically.
        /// Value MUST be between 50% and 100%
        /// (Limit 1000mb with 90% = quota increase when more than 900mb are used.)
        /// </summary>
        public int? AutoQuotaIncreaseThreshold { get; set; } = 75;

        /// <summary>
        /// It is a value in percent after which the quota is decreased automatically.
        /// Value MUST be between 0% and 50%
        /// (Limit 1000mb with 10% = quota decrese when less than 100mb are used.)
        /// </summary>
        public int? AutoQuotaDecreaseThreshold { get; set; } = 50;

        /// <summary>
        /// It is the portion of the quota added or substracted by a quota change.
        /// If the value exceeds the opposite boundary it should be capped in implementation.
        /// (The value should be larger than 1mb. For production maybe even larger than 10mb.)
        /// </summary>
        public ulong? AutoQuotaStepSizeInBytes { get; set; } = 10737418240;

        /// <summary>
        /// It is a time period in seconds until the next possible automatic quota change.
        /// (For production the value should be larger than an hour to prevent too many cycles.)
        /// </summary>
        public ulong? AutoQuotaLockPeriod { get; set; } = 28800;
    }

